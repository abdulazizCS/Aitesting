"""Build kb.js (the robot's knowledge base) from data/jazanu-site.md.

Usage: python3 tools/build_kb.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'data' / 'jazanu-site.md'
OUT = ROOT / 'kb.js'

# lines describing the scraping process rather than the university
META = re.compile(
    r'لم [يت]ُ?ستخرج|لم يُ?سترجع|لم تُ?سترجع|استنتاج|نتائج البحث|المحتوى المستخرج|الصفحة المسترجعة'
    r'|أنقل|كما ورد في المصدر|تعارض|الصفحة لا|لا يظهر|لا تذكر|لا تتضمن|لم تُعثر|لم يُذكر|غير مذكور|^ملاحظة|^تنبيه|^\*\*ملاحظة|^\*\*تنبيه|غير محسوم|لم يُتحقق|خلل في عرض'
)
SKIP_SECTIONS = re.compile(r'المحتويات|وثائق رسمية ذات صلة')


def clean(s):
    s = re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', s)          # md links
    s = s.replace('**', '').replace('`', '').replace('> ', '')
    s = re.sub(r'\((?=[^()]*[A-Za-z])[^()؀-ۿ]*\)', '', s)  # latin-only parentheticals
    s = re.sub(r'^\s*بدون تاريخ\s*\([^)]*\)\s*—\s*', '', s)  # undated news prefix
    s = re.sub(r'https?://\S+', '', s)
    s = re.sub(r'\s+', ' ', s).strip(' -–—:،')
    return s


def table_rows(lines):
    rows = [[c.strip() for c in l.strip().strip('|').split('|')] for l in lines]
    rows = [r for r in rows if not all(re.fullmatch(r':?-+:?', c) for c in r)]
    if len(rows) < 2:
        return []
    head, out = rows[0], []
    for r in rows[1:]:
        cells = [(h, clean(c)) for h, c in zip(head, r) if clean(c) and clean(c) not in ('—', '#')]
        if not cells:
            continue
        first = cells[0][1]
        rest = '، '.join(f'{clean(h)}: {c}' for h, c in cells[1:] if h != '#')
        if re.fullmatch(r'\d+', first) and len(cells) > 1:  # numbered rows: drop the index
            first, rest = cells[1][1], '، '.join(f'{clean(h)}: {c}' for h, c in cells[2:])
        out.append(f'{first} — {rest}' if rest else first)
    return out


def parse():
    sections, path, cur = [], {}, None
    lines = SRC.read_text(encoding='utf-8').splitlines()
    i = 0

    def flush():
        if cur and cur['facts'] and not SKIP_SECTIONS.search(cur['title']):
            sections.append(cur)

    while i < len(lines):
        line = lines[i]
        m = re.match(r'^(#{2,4})\s+(.*)', line)
        if m:
            flush()
            level, title = len(m.group(1)), clean(m.group(2))
            path[level] = title
            for k in list(path):
                if k > level:
                    del path[k]
            cur = {'title': title, 'path': [path[k] for k in sorted(path) if k < level], 'facts': [], 'src': ''}
            i += 1
            continue
        if cur is None:
            i += 1
            continue
        if line.startswith('المصدر:'):
            urls = re.findall(r'https?://[^\s،|]+', line)
            if urls and not cur['src']:
                cur['src'] = urls[0]
        elif line.lstrip().startswith('|'):
            block = []
            while i < len(lines) and lines[i].lstrip().startswith('|'):
                block.append(lines[i])
                i += 1
            cur['facts'] += table_rows(block)
            continue
        elif re.match(r'^\s*([-*]|\d+\.)\s+', line):
            indent = len(line) - len(line.lstrip())
            text = clean(re.sub(r'^\s*([-*]|\d+\.)\s+', '', line))
            # gather nested children into the parent fact
            children = []
            j = i + 1
            while j < len(lines) and re.match(r'^\s*([-*]|\d+\.)\s+', lines[j]) \
                    and len(lines[j]) - len(lines[j].lstrip()) > indent:
                c = clean(re.sub(r'^\s*([-*]|\d+\.)\s+', '', lines[j]))
                if c and not META.search(c):
                    children.append(c.rstrip('.'))
                j += 1
            if text and not META.search(text):
                if children:
                    sep = ' ' if text.endswith(':') else ': '
                    text = text.rstrip(':.') + sep.rstrip() + ' ' + '، '.join(children) + '.'
                cur['facts'].append(text)
            elif children and not text:
                cur['facts'] += children
            i = j
            continue
        elif line.lstrip().startswith('>') and cur['facts'] and len(cur['facts'][-1]) < 40:
            cur['facts'][-1] = cur['facts'][-1].rstrip(':') + ': ' + clean(line.lstrip()[1:])
        elif line.strip() and not line.startswith('---'):
            t = clean(line)
            if t and not META.search(t):
                cur['facts'] += [s.strip() for s in re.split(r'(?<=[.!؟])\s+', t) if len(s.strip()) > 8]
        i += 1
    flush()
    for s in sections:
        s['facts'] = [f for f in dict.fromkeys(s['facts']) if len(f) > 3]
    return [s for s in sections if s['facts']]


if __name__ == '__main__':
    kb = parse()
    OUT.write_text('// Generated by tools/build_kb.py from data/jazanu-site.md — do not edit by hand.\n'
                   'export const KB = ' + json.dumps(kb, ensure_ascii=False, indent=0) + ';\n', encoding='utf-8')
    print(f'{len(kb)} sections, {sum(len(s["facts"]) for s in kb)} facts, {OUT.stat().st_size // 1024} KB')
